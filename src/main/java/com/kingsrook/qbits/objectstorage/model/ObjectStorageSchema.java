package com.kingsrook.qbits.objectstorage.model;


import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import com.kingsrook.qbits.objectstorage.ObjectStorageQBitConfig;
import com.kingsrook.qqq.backend.core.instances.QInstanceEnricher;
import com.kingsrook.qqq.backend.core.model.metadata.fields.QFieldMetaData;
import com.kingsrook.qqq.backend.core.model.metadata.tables.QTableMetaData;


/*******************************************************************************
 ** The PostgreSQL schema of the qbit's tables, generated from the same metadata
 ** the app runs on, so an adopter's migration (Liquibase, Flyway) cannot drift
 ** from the tables. Column names are the snake_case of the field names (what the
 ** QQQ RDBMS backend uses), table names are the QQQ table names.
 **
 ** The statements are idempotent (CREATE ... IF NOT EXISTS) and include the
 ** unique constraints and the browse indexes the design calls for
 ** ((bucket, key) unique; bucket with folder, last modified, size, content type),
 ** then the foreign keys, each in a block that also upgrades an existing schema
 ** (orphans recorded in qqq_fk_quarantine first; see addForeignKey).
 *******************************************************************************/
public final class ObjectStorageSchema
{
   /** Unique constraints: table to column lists. */
   private static final Map<String, List<List<String>>> UNIQUES = Map.of(
      ObjectStorageTables.CONNECTION, List.of(List.of("name")),
      ObjectStorageTables.BUCKET, List.of(List.of("alias")),
      ObjectStorageTables.CONNECTION_CAPABILITY, List.of(List.of("connectionId", "capability")),
      ObjectStorageTables.BUCKET_CAPABILITY, List.of(List.of("bucketId", "capability")),
      ObjectStorageTables.FOLDER, List.of(List.of("bucketId", "path")),
      ObjectStorageTables.OBJECT, List.of(List.of("bucketId", "objectKey")),
      ObjectStorageTables.USAGE_DAILY, List.of(List.of("bucketId", "snapshotDate")));

   /** Browse and lookup indexes: table to column lists. New entries go at the end of
    ** a table's list, so the generated names (ix_<table>_<n>) of existing ones never change.
    ** The child lists on record pages (folder -> objects, object -> versions and references)
    ** filter on the parent id alone, so those columns lead an index of their own. */
   private static final Map<String, List<List<String>>> INDEXES = Map.of(
      ObjectStorageTables.OBJECT, List.of(List.of("bucketId", "folderId"), List.of("bucketId", "lastModified"), List.of("bucketId", "size"), List.of("bucketId", "contentType"),
         List.of("bucketId", "deleted", "referenceCount"), List.of("bucketId", "headersKnown", "deleted"), List.of("folderId")),
      ObjectStorageTables.OBJECT_REFERENCE, List.of(List.of("bucketId", "objectId"), List.of("bucketId", "missing"), List.of("objectId")),
      ObjectStorageTables.OPERATION, List.of(List.of("bucketId", "occurredAt"), List.of("objectKey", "occurredAt")),
      ObjectStorageTables.FOLDER, List.of(List.of("parentFolderId")),
      ObjectStorageTables.OBJECT_VERSION, List.of(List.of("bucketId", "objectKey"), List.of("objectId")),
      ObjectStorageTables.BUCKET, List.of(List.of("connectionId")),
      ObjectStorageTables.HEADER_RULE, List.of(List.of("bucketId")),
      ObjectStorageTables.PROTECTION_RULE, List.of(List.of("bucketId")));

   /** The table that records the rows an upgrade changed so a foreign key could be added
    ** (identical DDL in every qbit, so whichever runs first creates it). */
   public static final String QUARANTINE_DDL = "CREATE TABLE IF NOT EXISTS qqq_fk_quarantine (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
      + "table_name VARCHAR(100) NOT NULL, column_name VARCHAR(100) NOT NULL, row_id VARCHAR(100), missing_parent_id VARCHAR(100), action VARCHAR(20) NOT NULL, "
      + "row_data TEXT, changeset VARCHAR(200), quarantined_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP)";

   /** Every parent/child relation, enforced in the database. The qbit never deletes a
    ** connection, bucket or folder row (ConfigSync only upserts; folders are only
    ** created), and its only deletes are object rows (scan removal, trash retention,
    ** hard-delete write-through) and reference rows (rebuilt by each reference scan),
    ** through QQQ deletes with no associations. So:
    ** - observed state that belongs to a parent (capabilities, folders, objects, versions,
    **   usage) CASCADEs: an object delete takes its versions, and an admin deleting a
    **   bucket row takes its index with it;
    ** - optional pointers into the index (object.folderId, reference.objectId) SET NULL:
    **   the next scan sets the folder again, and a reference to a removed object is
    **   missing until the next reference scan rebuilds the rows;
    ** - admin-authored config (header and protection rules), the operation audit log and
    **   a bucket's connection RESTRICT (NO ACTION): deleting a bucket row that has rules
    **   or history, or a connection that buckets use, is refused rather than silently
    **   dropping protection or audit rows (ConfigSync would re-create a configured bucket
    **   under a new id, with its rules gone).
    ** Inserts are parents first everywhere (connections before buckets, a folder's parent
    ** before the folder, folders before objects), so nothing needs to be deferred.
    ** New entries go at the end. */
   private static final List<ForeignKey> FOREIGN_KEYS = List.of(
      new ForeignKey(ObjectStorageTables.BUCKET, "connectionId", ObjectStorageTables.CONNECTION, "NO ACTION"),
      new ForeignKey(ObjectStorageTables.CONNECTION_CAPABILITY, "connectionId", ObjectStorageTables.CONNECTION, "CASCADE"),
      new ForeignKey(ObjectStorageTables.BUCKET_CAPABILITY, "bucketId", ObjectStorageTables.BUCKET, "CASCADE"),
      new ForeignKey(ObjectStorageTables.HEADER_RULE, "bucketId", ObjectStorageTables.BUCKET, "NO ACTION"),
      new ForeignKey(ObjectStorageTables.PROTECTION_RULE, "bucketId", ObjectStorageTables.BUCKET, "NO ACTION"),
      new ForeignKey(ObjectStorageTables.OPERATION, "bucketId", ObjectStorageTables.BUCKET, "NO ACTION"),
      new ForeignKey(ObjectStorageTables.USAGE_DAILY, "bucketId", ObjectStorageTables.BUCKET, "CASCADE"),
      new ForeignKey(ObjectStorageTables.FOLDER, "bucketId", ObjectStorageTables.BUCKET, "CASCADE"),
      new ForeignKey(ObjectStorageTables.FOLDER, "parentFolderId", ObjectStorageTables.FOLDER, "CASCADE"),
      new ForeignKey(ObjectStorageTables.OBJECT, "bucketId", ObjectStorageTables.BUCKET, "CASCADE"),
      new ForeignKey(ObjectStorageTables.OBJECT, "folderId", ObjectStorageTables.FOLDER, "SET NULL"),
      new ForeignKey(ObjectStorageTables.OBJECT_VERSION, "bucketId", ObjectStorageTables.BUCKET, "CASCADE"),
      new ForeignKey(ObjectStorageTables.OBJECT_VERSION, "objectId", ObjectStorageTables.OBJECT, "CASCADE"),
      new ForeignKey(ObjectStorageTables.OBJECT_REFERENCE, "bucketId", ObjectStorageTables.BUCKET, "CASCADE"),
      new ForeignKey(ObjectStorageTables.OBJECT_REFERENCE, "objectId", ObjectStorageTables.OBJECT, "SET NULL"));



   /*******************************************************************************
    ** One foreign key: the child table and field, the parent table (always its id)
    ** and the ON DELETE rule.
    *******************************************************************************/
   public record ForeignKey(String table, String field, String parent, String onDelete)
   {
      /*******************************************************************************
       ** The constraint name: fk_<child table>_<child column>.
       *******************************************************************************/
      public String name()
      {
         return ("fk_" + table + "_" + column(field));
      }
   }



   /*******************************************************************************
    ** Utility class.
    *******************************************************************************/
   private ObjectStorageSchema()
   {
   }



   /*******************************************************************************
    ** The CREATE TABLE and CREATE INDEX statements for every qbit table, in
    ** dependency order, one statement per list entry.
    *******************************************************************************/
   public static List<String> postgresStatements(ObjectStorageQBitConfig config)
   {
      List<String> statements = new ArrayList<>();
      List<String> order = List.of(ObjectStorageTables.CONNECTION, ObjectStorageTables.CONNECTION_CAPABILITY, ObjectStorageTables.BUCKET, ObjectStorageTables.BUCKET_CAPABILITY,
         ObjectStorageTables.FOLDER, ObjectStorageTables.OBJECT, ObjectStorageTables.OBJECT_VERSION, ObjectStorageTables.OBJECT_REFERENCE, ObjectStorageTables.HEADER_RULE,
         ObjectStorageTables.PROTECTION_RULE, ObjectStorageTables.OPERATION, ObjectStorageTables.USAGE_DAILY);
      List<QTableMetaData> tables = ObjectStorageTables.tables(config);
      for(String name : order)
      {
         for(QTableMetaData table : tables)
         {
            if(table.getName().equals(name))
            {
               statements.add(createTable(table));
               int n = 0;
               for(List<String> columns : INDEXES.getOrDefault(name, List.of()))
               {
                  n++;
                  statements.add("CREATE INDEX IF NOT EXISTS ix_" + name + "_" + n + " ON " + name + " (" + String.join(", ", columns.stream().map(ObjectStorageSchema::column).toList()) + ")");
               }
            }
         }
      }
      statements.add(QUARANTINE_DDL);
      for(ForeignKey fk : FOREIGN_KEYS)
      {
         statements.add(addForeignKey(fk, tables));
      }
      return (statements);
   }



   /*******************************************************************************
    ** The foreign keys the schema declares.
    *******************************************************************************/
   public static List<ForeignKey> foreignKeys()
   {
      return (FOREIGN_KEYS);
   }



   /*******************************************************************************
    ** One idempotent block that adds a foreign key and upgrades an existing schema
    ** safely: rows whose parent is gone are first recorded in qqq_fk_quarantine, then
    ** their reference is cleared (nullable column) or the row is deleted (required
    ** column; the whole row is recorded), so adding the constraint cannot fail. A
    ** no-op once the constraint exists.
    *******************************************************************************/
   private static String addForeignKey(ForeignKey fk, List<QTableMetaData> tables)
   {
      String  col      = column(fk.field());
      boolean required = tables.stream().filter(t -> t.getName().equals(fk.table())).findFirst()
         .map(t -> Boolean.TRUE.equals(t.getField(fk.field()).getIsRequired())).orElse(false);
      String  orphans  = "c." + col + " IS NOT NULL AND NOT EXISTS (SELECT 1 FROM " + fk.parent() + " p WHERE p.id = c." + col + ")";
      return ("DO $$\n"
         + "BEGIN\n"
         + "   IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = '" + fk.name() + "' AND conrelid = '" + fk.table() + "'::regclass) THEN\n"
         + "      INSERT INTO qqq_fk_quarantine (table_name, column_name, row_id, missing_parent_id, action, row_data, changeset)\n"
         + "         SELECT '" + fk.table() + "', '" + col + "', c.id::text, c." + col + "::text, '" + (required ? "DELETED" : "NULLED") + "', row_to_json(c)::text, "
         + "'qbit-object-storage ObjectStorageSchema'\n"
         + "         FROM " + fk.table() + " c WHERE " + orphans + ";\n"
         + (required
            ? "      DELETE FROM " + fk.table() + " c WHERE " + orphans + ";\n"
            : "      UPDATE " + fk.table() + " c SET " + col + " = NULL WHERE " + orphans + ";\n")
         + "      ALTER TABLE " + fk.table() + " ADD CONSTRAINT " + fk.name() + " FOREIGN KEY (" + col + ") REFERENCES " + fk.parent() + " (id) ON DELETE " + fk.onDelete() + ";\n"
         + "   END IF;\n"
         + "END $$");
   }



   /*******************************************************************************
    ** The statements as one script.
    *******************************************************************************/
   public static String postgresScript(ObjectStorageQBitConfig config)
   {
      return (String.join(";\n", postgresStatements(config)) + ";\n");
   }



   /*******************************************************************************
    ** One table.
    *******************************************************************************/
   private static String createTable(QTableMetaData table)
   {
      List<String> lines = new ArrayList<>();
      for(QFieldMetaData field : table.getFields().values())
      {
         if("id".equals(field.getName()))
         {
            lines.add("   id INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL");
            continue;
         }
         lines.add("   " + column(field.getName()) + " " + sqlType(field) + (Boolean.TRUE.equals(field.getIsRequired()) ? " NOT NULL" : ""));
      }
      lines.add("   CONSTRAINT pk_" + table.getName() + " PRIMARY KEY (id)");
      int n = 0;
      for(List<String> columns : UNIQUES.getOrDefault(table.getName(), List.of()))
      {
         n++;
         lines.add("   CONSTRAINT uq_" + table.getName() + "_" + n + " UNIQUE (" + String.join(", ", columns.stream().map(ObjectStorageSchema::column).toList()) + ")");
      }
      return ("CREATE TABLE IF NOT EXISTS " + table.getName() + " (\n" + String.join(",\n", lines) + "\n)");
   }



   /*******************************************************************************
    ** The snake_case column of a field name.
    *******************************************************************************/
   static String column(String fieldName)
   {
      return (QInstanceEnricher.inferBackendName(fieldName));
   }



   /*******************************************************************************
    ** The PostgreSQL type of a field.
    *******************************************************************************/
   private static String sqlType(QFieldMetaData field)
   {
      return (switch(field.getType())
      {
         case INTEGER -> "INTEGER";
         case LONG -> "BIGINT";
         case BOOLEAN -> "BOOLEAN";
         case DATE -> "DATE";
         case DATE_TIME -> "TIMESTAMP WITHOUT TIME ZONE";
         case TEXT, HTML -> "TEXT";
         case DECIMAL -> "NUMERIC(18,4)";
         default -> "VARCHAR(" + (field.getMaxLength() == null ? 250 : field.getMaxLength()) + ")";
      });
   }
}
